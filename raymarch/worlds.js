/*
* @param {Function[]} effects effects applied after a ray finishes its march
* @param {Number[]} sunVector the angle of the sun in [theta, phi] form.
* @param {Number[]} spawn 
* @param {Scene3dObject[]} objects 
* @param {Number|none} shadowPercent a number from 0 to 1 representing the brightness of shadowed areas. At 0, shadows do nothing. At 1, shadows are pure black.
*/

class World {
	/**
	 * Creates a World object
	 * @param {Function|0} tickFunc optional function to execute when ticking. Passing in 0 means no function.
	 * @param {String} worldParams world params: name, effects, sunvector, shadowPercent, spawn
	 * @param {String} objParams string object params for the first object. Add more arguments for more objects.
	 */
	constructor(tickFunc, worldParams, objParams1, objParams2, objParams3) {
		this.tickFunc = (tickFunc === 0) ? null : tickFunc;

		this.name;
		this.postEffects = [];
		this.svSet = [0,1.5];
		this.spawn = Pos(0,0,0);
		this.ambientLight = 1 - render_shadowPercent;

		var params = worldParams;

		//everything other than arg1 is objects
		this.objects = Array.from(arguments).slice(2);
		//objects is the set of base objects that makes the world, while 
		//expressed objects is everything that could currently contribute to the world SDF.
		//this is because a single object could be made of multiple overlapping SDFs, 
		//or an object could decide to unload itself and not contribute at all
		this.expObjs = [];
		this.shouldRegen = false;
		
		this.id = null;
		this.sunVector = null;
		this.bvh = null;

		this.errorCheck();
		this.finalize(params);
	}
	
	errorCheck() {
		const wname = this.name;
		function larg(obj, val, name) {
			if (obj.length >= val) {
				console.error(`World ${wname}: too many ${name}s!`);
				obj.splice(val);
			}
		}

		larg(worldsByID, world_maxID, `world`);
		larg(this.postEffects, texture_worldCols, `post-effect`);
		larg(this.expObjs, texture_worldCols, `object`);
	}
	
	finalize(paramStr) {
		this.postEffects = [];
		this.spawn = [0,0,0];
		this.svSet = [0,1.5];
		this.ambientLight = 1 - render_shadowPercent;

		//deserialize params
		const spaceOrTab = /[\s\t]/;
		var spl = paramStr.split(`\n`);

		//first line is always name
		this.name = spl[0].slice(0, -1);

		//second line is preEffects
		var tabStop = spl[1].lastIndexOf(`\t`);
		var c = 1;
		while (spl[c][tabStop] == `\t`) {
			//stupid preeffect parse
			var effSpl = spl[c].slice(tabStop + 1).split(spaceOrTab);
			if (effSpl[0] == `//`) {
				c += 1;
				continue;
			}
			this.postEffects.push([eval(effSpl[0]), ...(effSpl.slice(1).map(a => JSON.parse(a)))]);
			c += 1;
		}
		//now parse non-effects
		while (spl[c]) {
			var tagSpl = spl[c].slice(tabStop).split(spaceOrTab);
			switch (tagSpl[0]) {
				case `sun:`:
					this.svSet[0] = +tagSpl[1];
					this.svSet[1] = +tagSpl[2];
					break;
				case `spawn:`:
					for (var l=1; l<tagSpl.length; l++) {
						this.spawn[l-1] = +tagSpl[l];
					}
					break;
				case `shadow:`:
					this.ambientLight = 1 - tagSpl[1]
					break;
			} 
			c += 1;
		}

		//deserialize objects
		for (var o=0; o<this.objects.length; o++) {
			if (this.objects[o].constructor.name == "String") {
				this.objects[o] = deserialize(this.objects[o]);
			}
		}

		this.id = worlds[this.name] ? worlds[this.name].id : worldsByID.length;
		worlds[this.name] = this;
		worldsByID[this.id] = this;
		
		this.bvh = new BVH(this);
		this.generate();
		console.log(`finished ${this.name}!`);
	}
	
	serialize() {
		var effStrs = [];
		this.postEffects.forEach(e => {
			var str = map_effStr[e[0]];
			for (var f=1; f<e.length; f++) {
				if (e[f].length) {
					str += ` [${e[f]}]`;
				} else {
					str += ` ${e[f]}`;
				}
			}
			effStrs.push(str);
		});

		const spn = this.spawn;
		var spawnStr = `${spn[0]} ${spn[1]} ${spn[2]}`;
		if (this.spawn.length > 3) {
			spawnStr += ` ${spn[3]} ${spn[4]}`;
		}
	
		var properties = `${this.name}:
			${effStrs.join(`\n\t\t\t`)}
		sun:	${this.svSet[0]} ${this.svSet[1]}
		shadow:	${1 - this.ambientLight}
		spawn:	${spawnStr}\``;

		var objs = this.objects.map(a => a.serialize()).join("`,\n`");
		return "`" + properties + ",\n`" + objs + "`";
	}

	express() {
		var expObjs = [];
		this.expObjs = expObjs;
		this.objects.forEach(o => {
			o.express().forEach(q => {
				expObjs.push(q);
			});
		});
		if (debug_flags.showGrid && editor_selected != player) {
			const r = Math.round;
			var eDist = editor_flags.gridDist;
			while (eDist < 6) {
				eDist *= 2;
			}
			const heDist = eDist/2;
			const center = Pos(
				r(editor_selected.pos[0] / eDist) * eDist,
				r(editor_selected.pos[1] / eDist) * eDist,
				r(editor_selected.pos[2] / eDist) * eDist,
			);
			const gd = 3;
			var create = (x, y, z, rx, ry, rz) => {
				expObjs.push(createDescribedObject(TYPE_BOXFRAME, {
					pos: Pos(x, y, z), rx: rx, ry: ry, rz: rz,
					e: 0.4,
					material: new M_Plexiglass(255, 0, 255, 25),
					intangible: true,
				}));
			}
			for (var a=-gd; a<gd; a++) {
				for (var b=-gd; b<gd; b++) {
					create(
						center[0] + eDist*(a+0.5), center[1] + eDist*(b+0.5), center[2],
						heDist, heDist, 0
					);
					create(
						center[0] + eDist*(a+0.5), center[1], center[2] + eDist*(b+0.5),
						heDist, 0, heDist
					);
					create(
						center[0], center[1] + eDist*(a+0.5), center[2] + eDist*(b+0.5),
						0, heDist, heDist
					);
				}
			}
		}
	}

	fixBounds(reset) {
		if (reset) {
			this.expObjs.forEach(o => {
				o.gloopExt = 0;
			});
			return;
		}
		
		/*there are some things that push SDFs outside of their normal bounds. These are Gloopy objects and Smooth objects.
		Smooth objects are simple, because they just enhance a single object's bounds. 
		However, Gloopy objects expand the bounds of anything they touch, and so make sense as global state.
		*/
		const max = Math.max;
		const bvh = this.bvh;
		const objs = this.expObjs;
		objs.forEach(o => {
			if (o.nature & N_GLOOP) {
				o.gloopExt = max(o.gloopExt, o.gloopiness);
				//find all objects within twice the gloopy range and make sure their extGloop value is proper
				var box = o.bounds();
				var affected = bvh.objectsInBox(box[0], box[1]);
				affected.forEach(a => {
					//it's only really affected if a comes before o (because of how glooping is calculated)
					if (objs.indexOf(a) < objs.indexOf(o)) {
						a.gloopExt = max(a.gloopExt, o.gloopiness);
					}
				});
			}
		});
	}

	generate() {
		this.sunVector = polToCart(this.svSet[0], this.svSet[1], 1);
		this.express();
		//TODO: this is a terrible way to do this. Do it differently
		this.fixBounds(true);
		this.bvh.generate();
		if (debug_flags.showObjBounds) {
			var nodes = [this.bvh.root];
			while (nodes.length > 0) {
				var curr = nodes.pop();
				if (curr.left) {
					nodes.push(curr.left);
				}
				if (curr.right) {
					nodes.push(curr.right);
				}
				if (!curr.left && !curr.right) {
					var b = [curr.minPos, curr.maxPos];
					var mid = Pos(
						(b[0][0] + b[1][0]) / 2,
						(b[0][1] + b[1][1]) / 2,
						(b[0][2] + b[1][2]) / 2,
					);
					const rx = mid[0] - b[0][0];
					const ry = mid[1] - b[0][1];
					const rz = mid[2] - b[0][2];
					var frame = new BoxFrame({pos: mid, theta: 0, phi: 0, rot: 0}, createDefaultMaterial(), N_NORMAL, rx, ry, rz, 2);
					this.expObjs.push(frame);
				}
			}
		}
		this.fixBounds(false);
		this.bvh.generate();
	}
	
	//estimate distance at a given point. Returns both distance and the object that gave that distance
	estimateObj(obj) {
		return sceneSDF(this.objects);
	}
	
	estimatePos(pos) {
		var dist = 1e100;
		var distInd = -1;
		for (var i=0; i<this.expObjs.length; i++) {
			var testDist = this.expObjs[i].distanceToPos(pos);
			if (testDist < dist) {
				dist = testDist;
				distInd = i;
			}
			//if the distance is small enough, don't bother running through all the other objects
			if (dist < -2) {
				return [dist, distInd];
			}
		}
		return [dist, distInd];
	}
	
	/**
	* returns the top 2 indices and their distances, instead of just the top one
	 */
	estimatePosRanking(pos) {
		var dist_2nd = 1e100;
		var dind_2nd = -1;
		var dist = 1e99;
		var dind = -1;
		const expObjs = this.expObjs;
		for (var i=0; i<expObjs.length; i++) {
			const testDist = expObjs[i].distanceToPos(pos);
			if (testDist < dist) {
				dist_2nd = dist;
				dind_2nd = dind;
				dist = testDist;
				dind = i;
			} else if (testDist < dist_2nd) {
				dist_2nd = testDist;
				dind_2nd = i;
			}
		}
		return [[dist, dind], [dist_2nd, dind_2nd]];
	}
	
	tick() {
		// this.tree.update();
		if (loading_world == this) {
			if (this.tickFunc) {
				this.tickFunc();
			}
		}
		if (this.shouldRegen) {
			this.generate();
			createGPUWorld(this);
			this.shouldRegen = false;
		}
	}
}

